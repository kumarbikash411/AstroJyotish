export function translate(language: LanguageCode, key: TranslationKey): string {
  const translation = translations[language]?.[key] ?? extendedTranslations[language]?.[key];
  if (translation) return translation;
  if (key === "privacyDetails" || key === "birthAccuracy") {
    return privacyTranslations[language]?.[key] ?? english[key];
  }
  if (key === "homeReading" || key === "removeSampleLimit") {
    return homeTranslations[language]?.[key] ?? english[key];
  }
  return english[key];
}

export function getLanguage(code: string): (typeof languages)[number] {
  return languages.find((language) => language.code === code) ?? languages[0];
}
